// Generates docs/THIRD_PARTY_LICENSES.md from `cargo metadata` + package-lock.json.
// No extra tools: both already carry each package's declared licence.
//   node scripts/license_report.mjs
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

// Licences that need a decision before a closed-source sale (copyleft or unknown).
const REVIEW = /GPL|MPL|EPL|CDDL|CC-BY-SA|SSPL|BUSL|Commons-Clause|UNLICENSED|UNKNOWN/i;
// SPDX "A OR B": if any branch is permissive we may pick it.
const ok = (lic) => lic.split(/\s+OR\s+|\//).some((l) => !REVIEW.test(l.replace(/[()]/g, "")));

const cargo = JSON.parse(execSync(
  "cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc",
  { cwd: "src-tauri", maxBuffer: 1 << 28 }).toString());
const rust = cargo.packages
  .filter((p) => p.name !== "worldforge2")
  .map((p) => ({ name: p.name, version: p.version, license: p.license || (p.license_file ? `file: ${p.license_file}` : "UNKNOWN") }));

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const js = Object.entries(lock.packages)
  .filter(([path, p]) => path && !p.dev) // shipped (non-dev) packages only
  .map(([path, p]) => ({ name: path.replace(/^.*node_modules\//, ""), version: p.version, license: p.license || "UNKNOWN" }));

function section(title, rows) {
  const counts = {};
  for (const r of rows) counts[r.license] = (counts[r.license] || 0) + 1;
  const flagged = rows.filter((r) => !ok(r.license));
  let s = `## ${title} (${rows.length} packages)\n\n| Licence | Packages |\n|---|---|\n`;
  for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) s += `| ${l} | ${n} |\n`;
  s += `\n**Needs review before sale: ${flagged.length}**\n\n`;
  for (const r of flagged) s += `- \`${r.name}\` ${r.version} — ${r.license}\n`;
  s += `\n<details><summary>Full list</summary>\n\n| Package | Version | Licence |\n|---|---|---|\n`;
  for (const r of rows.sort((a, b) => a.name.localeCompare(b.name))) s += `| ${r.name} | ${r.version} | ${r.license} |\n`;
  return s + `\n</details>\n\n`;
}

const out = `# Third-party licences

Generated by \`node scripts/license_report.mjs\` on ${new Date().toISOString().slice(0, 10)} —
re-run it after any dependency change. Rust: every crate resolved for the Windows target
(includes build-time crates, a superset of what ships). JavaScript: non-dev packages from
\`package-lock.json\`. "Needs review" = copyleft or undeclared licence; an \`A OR B\`
licence with a permissive branch is not flagged. This is an inventory, not legal advice.

**Current reading:** the only flagged crates are MPL-2.0, pulled in by Tauri itself
(HTML/CSS parsing). MPL-2.0 is *file-level* copyleft: it may ship inside a closed-source
binary as long as those crates are used unmodified and buyers are told where their source
is (crates.io). Keep them unmodified, and keep the EULA/about box pointing here.

${section("Rust crates", rust)}${section("JavaScript packages", js)}`;
writeFileSync("docs/THIRD_PARTY_LICENSES.md", out);
console.log(`rust ${rust.length}, js ${js.length}, flagged ${[...rust, ...js].filter((r) => !ok(r.license)).length}`);
